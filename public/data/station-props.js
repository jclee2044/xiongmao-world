export function stationPropScenery(scale) {
  return stationProps.map(p => {
    const points = [...p.opaque, ...p.foliage].flat();
    const xs = points.map(v => v[0]), ys = points.map(v => v[1]);
    const left = Math.min(...xs), right = Math.max(...xs);
    const top = Math.min(...ys), bottom = Math.max(...ys);
    return { type: 'station-prop', id: p.id, prop: p,
      x: (left + right) / 2 * scale, y: bottom * scale,
      w: (right - left) * scale, h: (bottom - top) * scale,
      artY: p.depth * scale };
  });
}
export function stationPropSolids(scale) {
  return stationProps.filter(p => p.footprint.length).map(p => p.footprint.map(([x,y]) => [x*scale,y*scale]));
}
