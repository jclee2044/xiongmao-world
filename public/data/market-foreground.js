export function marketForeground(plate) {
  if (!plate) return [];
  return outlines.map(({ id, outline }) => ({
    id: `market-foreground-${id}`,
    polygon: outline.map(([x, y]) => [
      plate.x + x * plate.w / 1536,
      plate.y + y * plate.h / 1024,
    ]),
  }));
}

// Compare feet with the front edge at this horizontal position. A single
// depth for an entire sloping facade would incorrectly hide its shopkeeper.
export function behindMarketForeground(polygon, x, y, halfWidth = 0) {
  const left = Math.min(...polygon.map(([px]) => px));
  const right = Math.max(...polygon.map(([px]) => px));
  if (x + halfWidth < left || x - halfWidth > right) return false;
  // A shoulder can overlap foliage even when the feet are just beside it.
  x = Math.max(left, Math.min(right, x));
  let front = -Infinity;
  for (let i = 0; i < polygon.length; i++) {
    const [ax, ay] = polygon[i];
    const [bx, by] = polygon[(i + 1) % polygon.length];
    if (x < Math.min(ax, bx) || x > Math.max(ax, bx)) continue;
    front = Math.max(front, ax === bx ? Math.max(ay, by) :
      ay + (by - ay) * (x - ax) / (bx - ax));
  }
  return y < front;
}
