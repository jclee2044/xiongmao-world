import assert from "node:assert/strict";
import { chromium } from "playwright";
import { Store, newState } from "../server/store.js";
import { createApp } from "../server/index.js";
import { scenes } from "../public/game/world.js";
import { enterWorld } from "./browser-helpers.js";
const server=createApp({store:new Store(":memory:"),providerConfig:{provider:"story"}});
await new Promise(r=>server.listen(0,"127.0.0.1",r));
const base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({executablePath:"/usr/bin/chromium",headless:true,args:["--no-sandbox","--mute-audio"]});
const errors=[];
try {
  const context=await browser.newContext({viewport:{width:1280,height:900},serviceWorkers:"block"});
  const initial=await (await context.request.get(base+"/api/state")).json();
  const fox=scenes.shanghai.interactables.find(o=>o.id==="fox-plush");
  const state=newState();
  state.position={x:fox.x,y:fox.y+90};
  Object.assign(state.settings,{music:0,ambience:0,voice:false});
  const save=await context.request.post(base+"/api/state",{headers:{Origin:base},data:{revision:initial.revision,state}});
  assert.equal(save.status(),200);
  const page=await context.newPage();
  page.on("pageerror",e=>{errors.push(e.message); console.error(e.stack);});
  await page.goto(base);
  await enterWorld(page);
  await page.keyboard.down("ArrowUp");
  await page.waitForTimeout(250);
  await page.keyboard.up("ArrowUp");
  await page.locator("#panda-speech").waitFor({state:"visible"});
  await page.screenshot({path:"test-results/fox-hidden-bamboo.png"});
  await page.keyboard.press("e");
  await page.locator("#bring-home").waitFor({state:"visible"});
  assert.ok((await page.locator("#panel").textContent()).includes("小狐狸"));
  assert.equal(await page.locator("#bring-home").textContent(), "收集 Collect");
  assert.equal(await page.locator(".collectible-reveal").getAttribute("src"), "/assets/characters/fox-plush.png");
  await page.locator('#panel [data-close="panel"]').click();
  await page.waitForTimeout(700);
  const uncollected=await(await context.request.get(base+"/api/state")).json();
  assert.deepEqual(uncollected.state.found,[]);
  await page.keyboard.press("e");
  await page.locator("#bring-home").waitFor({state:"visible"});
  await page.locator("#bring-home").click();
  await page.waitForFunction(()=>document.querySelector("#world").dataset.scene==="home" && document.querySelector("#world").dataset.artReady==="true").catch(async e=>{await page.screenshot({path:"test-results/fox-home-failure.png"});console.log(await page.locator("body").innerText());throw e;});
  await page.waitForTimeout(1000);
  await page.screenshot({path:"test-results/fox-at-home.png"});
  await page.waitForFunction(async()=>{const s=await(await fetch("/api/state")).json();return s.state.found.includes("fox-plush")&&s.state.scene==="home";});
  await page.reload();
  await enterWorld(page);
  assert.equal(await page.locator("#world").getAttribute("data-scene"),"home");
  const saved=await(await context.request.get(base+"/api/state")).json();
  assert.deepEqual(saved.state.found,["fox-plush"]);
  const outsideContext=await browser.newContext({viewport:{width:1280,height:900},serviceWorkers:"block"});
  const outsideInitial=await(await outsideContext.request.get(base+"/api/state")).json();
  const yard=scenes.shanghai.enclosures.find(o=>o.id==="bamboo-grove");
  const outsideState=newState();
  outsideState.position={x:yard.x+yard.w+35,y:fox.y};
  Object.assign(outsideState.settings,{music:0,ambience:0,voice:false});
  const outsideSave=await outsideContext.request.post(base+"/api/state",{headers:{Origin:base},data:{revision:outsideInitial.revision,state:outsideState}});
  assert.equal(outsideSave.status(),200);
  const outsidePage=await outsideContext.newPage();
  await outsidePage.goto(base);
  await enterWorld(outsidePage);
  await outsidePage.keyboard.down("ArrowUp");
  await outsidePage.waitForTimeout(100);
  await outsidePage.keyboard.up("ArrowUp");
  await outsidePage.keyboard.press("e");
  assert.equal(await outsidePage.locator("#panda-speech").isVisible(),false);
  assert.equal(await outsidePage.locator("#panel").isVisible(),false);
  assert.deepEqual(errors,[]);
  console.log("Fox hint, hidden pickup, home sprite, independent collection and reload passed.");
} finally {
  await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));
}
