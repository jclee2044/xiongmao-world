import {spawnSync} from "node:child_process";
import {writeFileSync} from "node:fs";
const source="public/assets/characters/station-travelers-walk-a-v1.png";
function magick(args){const r=spawnSync("magick",args,{maxBuffer:20000000});if(r.status!==0)throw Error(r.stderr.toString());return r.stdout;}
const [width,height]=magick(["identify","-format","%w %h",source]).toString().split(" ").map(Number);
const alpha=magick([source,"-alpha","extract","-depth","8","gray:-"]);
function gutter(axis, target, radius){
  const candidates=[];
  for(let n=Math.floor(target-radius);n<target+radius;n++){
    let empty=true;
    for(let m=0;m<(axis==="x"?height:width);m++)if(alpha[axis==="x"?m*width+n:n*width+m]>24){empty=false;break;}
    if(empty)candidates.push(n);
  }
  if(!candidates.length)throw Error(`Missing transparent ${axis} gutter`);
  return candidates[Math.floor(candidates.length/2)];
}
const columns=[0,gutter("x",width/3,width/16),gutter("x",width*2/3,width/16),width];
const rows=[0,gutter("y",height/2,height/12),height];
const art={};
for(const [row,id] of ["traveler-yutong","traveler-wenbo"].entries()){
  const frames=[];let top=height,bottom=0;
  for(let col=0;col<3;col++){
    let left=width,right=0;
    for(let y=rows[row];y<rows[row+1];y++)for(let x=columns[col];x<columns[col+1];x++)if(alpha[y*width+x]>24){
      left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
      if(x<=columns[col]+1||x>=columns[col+1]-2||y<=rows[row]+1||y>=rows[row+1]-2)throw Error(`Clipped sprite ${id}, ${col}`);
    }
    if(right<=left)throw Error(`Empty sprite ${id}, ${col}`);
    frames.push({x:left-2,w:right-left+5});
  }
  art[id]={sheet:"travelersWalkA",frames:frames.map(f=>({...f,y:top-2,h:bottom-top+5}))};
}
writeFileSync("public/data/station-traveler-walk-a-art.js","// Generated by scripts/prepare-station-traveler-walk-a.js; shared vertical anchors preserve scale.\nexport const travelerWalkAArt = "+JSON.stringify(art,null,2)+";\n");
magick([source,"-strip","-quality","85","-define","webp:alpha-quality=100","public/assets/optimized/station-travelers-walk-a-v1.webp"]);
console.log("Prepared Yutong and Wenbo: three walking frames each.");
