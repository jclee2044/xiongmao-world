// Measure the generated 3-column / 4-row walk atlas without changing its alpha.
// Shared row bounds and cell centers keep scale and ground anchors fixed.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const source = "public/assets/characters/station-travelers-walk-v1.png";
function magick(args) {
  const result = spawnSync("magick", args, {maxBuffer:20000000});
  if (result.status !== 0) throw Error(result.stderr.toString());
  return result.stdout;
}
const [width,height] = magick(["identify","-format","%w %h",source]).toString().split(" ").map(Number);
const alpha = magick([source,"-alpha","extract","-depth","8","gray:-"]);
// The painted atlas has slightly uneven row spacing. Split on real transparent
// gutters rather than clipping feet or including the next character's head.
const rowEdges = [0];
for (let row=1;row<4;row++) {
  const target=row*height/4, candidates=[];
  for(let y=Math.floor(target-height/16);y<target+height/16;y++) {
    let empty=true;
    for(let x=0;x<width;x++) if(alpha[y*width+x]>24) {empty=false;break;}
    if(empty) candidates.push(y);
  }
  if(!candidates.length) throw Error(`No transparent gutter before row ${row}`);
  rowEdges.push(candidates[Math.floor(candidates.length/2)]);
}
rowEdges.push(height);
const ids = ["traveler-rui","traveler-guoliang","traveler-yating","traveler-huilan"];
const art = {};
for (const [row,id] of ids.entries()) {
  const top = rowEdges[row], bottom = rowEdges[row+1];
  let minY=bottom, maxY=top, halfWidth=0;
  for (let col=0;col<3;col++) {
    const left=Math.floor(col*width/3), right=Math.floor((col+1)*width/3);
    const center=Math.floor((left+right)/2);
    let pixels=0;
    for (let y=top;y<bottom;y++) for(let x=left;x<right;x++) {
      if(alpha[y*width+x]<=24) continue;
      pixels++;
      minY=Math.min(minY,y);maxY=Math.max(maxY,y);
      halfWidth=Math.max(halfWidth,Math.abs(x-center));
      if(x<=left+1 || x>=right-2 || y<=top+1 || y>=bottom-2)
        throw Error(`Walking sprite touches cell edge: ${id}, frame ${col}`);
    }
    if(pixels<1000) throw Error(`Empty walking sprite: ${id}, frame ${col}`);
  }
  halfWidth+=2;
  art[id]={sheet:"travelersWalk",frames:Array.from({length:3},(_,col)=>({
    x:Math.floor((Math.floor(col*width/3)+Math.floor((col+1)*width/3))/2)-halfWidth,
    y:minY-2,w:halfWidth*2,h:maxY-minY+5,
  }))};
}
writeFileSync("public/data/station-traveler-walk-art.js", "// Generated by scripts/prepare-station-traveler-walk.js; stable anchors per character.\nimport { travelerWalkAArt } from \"./station-traveler-walk-a-art.js\";\nexport const travelerWalkArt = { ...travelerWalkAArt, ..."+JSON.stringify(art,null,2)+" };\n");
magick([source,"-strip","-quality","85","-define","webp:alpha-quality=100","public/assets/optimized/station-travelers-walk-v1.webp"]);
console.log("Prepared four station travelers with three dedicated walking frames each.");
