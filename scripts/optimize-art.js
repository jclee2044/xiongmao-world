// Rebuild browser-sized encodings without changing atlas dimensions or originals.
// Requires ImageMagick (magick); runtime has no image-processing dependency.
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
const sources = await Promise.all(
  [
    "public/game/render.js",
    "public/data/interiors.js",
    "public/data/town-rooms.js",
  ].map((p) => readFile(p, "utf8")),
);
const paths = [
  ...new Set(
    sources.flatMap((s) =>
      [...s.matchAll(/"(\/assets\/[^"\n]+\.(?:png|webp))"/g)].map((m) => m[1]),
    ),
  ),
];
await mkdir("public/assets/optimized", { recursive: true });
const manifest = {};
function convert(input, output, extra = []) {
  const result = spawnSync(
    "magick",
    [
      input,
      ...extra,
      "-strip",
      "-quality",
      "85",
      "-define",
      "webp:alpha-quality=100",
      output,
    ],
    { encoding: "utf8" },
  );
  if (result.status !== 0) throw new Error(result.stderr);
}
for (const path of paths) {
  const target =
    "/assets/optimized/" +
    path
      .split("/")
      .at(-1)
      .replace(/\.(png|webp)$/, ".webp");
  convert("public" + path, "public" + target);
  manifest[path] = target;
}
await writeFile(
  "public/data/optimized-art.js",
  "// Generated by scripts/optimize-art.js. Original dimensions and alpha retained.\nexport const optimizedArt = " +
    JSON.stringify(manifest, null, 2) +
    ";\n",
);
await mkdir("public/assets/welcome", { recursive: true });
for (const [name, path] of [
  ["town", "world/canal-lane.webp"],
  ["tea", "world/teahouse-interior.webp"],
  ["panda", "panda.png"],
]) {
  for (const width of name === "panda" ? [240] : [480, 960]) {
    convert(
      "public/assets/" + path,
      `public/assets/welcome/${name}-${width}.webp`,
      ["-resize", `${width}x>`],
    );
  }
}
console.log(`Optimized ${paths.length} game images and 5 welcome images.`);
