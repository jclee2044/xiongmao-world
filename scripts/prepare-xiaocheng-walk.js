// Preserve the generated alpha; measure equal cells without resizing sprites.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const source = "public/assets/characters/xiaocheng-walk.png";
function magick(args, options = {}) {
  const result = spawnSync("magick", args, { maxBuffer: 10000000, ...options });
  if (result.status !== 0) throw Error(result.stderr.toString());
  return result.stdout;
}
const [width, height] = magick(["identify", "-format", "%w %h", source])
  .toString()
  .split(" ")
  .map(Number);
const alpha = magick([source, "-alpha", "extract", "-depth", "8", "gray:-"]);
const cells = [];
for (let row = 0; row < 2; row++) {
  const frames = [];
  for (let col = 0; col < 4; col++) {
    const left = Math.floor((col * width) / 4),
      right = Math.floor(((col + 1) * width) / 4);
    const top = Math.floor((row * height) / 2),
      bottom = Math.floor(((row + 1) * height) / 2);
    let x0 = right,
      x1 = left,
      y0 = bottom,
      y1 = top;
    for (let y = top; y < bottom; y++)
      for (let x = left; x < right; x++)
        if (alpha[y * width + x] > 24) {
          x0 = Math.min(x0, x);
          x1 = Math.max(x1, x);
          y0 = Math.min(y0, y);
          y1 = Math.max(y1, y);
        }
    if (x1 <= x0 || y1 <= y0) throw Error(`Empty walking pose ${row},${col}`);
    frames.push({
      x: Math.max(left, x0 - 2),
      y: y0 - 2,
      w: Math.min(right, x1 + 3) - Math.max(left, x0 - 2),
      h: y1 - y0 + 5,
    });
  }
  cells.push(frames);
}
const art = {
  sheet: "xiaochengWalk",
  right: cells[0],
  away: cells[1],
  height: Math.max(...cells.flat().map((f) => f.h)),
};
writeFileSync(
  "public/data/xiaocheng-walk-art.js",
  "// Generated by scripts/prepare-xiaocheng-walk.js.\nexport const xiaochengWalkArt = " +
    JSON.stringify(art, null, 2) +
    ";\n",
);
magick([
  source,
  "-strip",
  "-quality",
  "85",
  "-define",
  "webp:alpha-quality=100",
  "public/assets/optimized/xiaocheng-walk.webp",
]);
console.log("Prepared Xiaocheng: two directions × four walking frames.");
