// Preserve generated alpha and a common scale/baseline for the three rear poses.
import {spawnSync} from "node:child_process";
import {writeFileSync} from "node:fs";
const source="public/assets/characters/wenbo-conversation-away-v1.png";
function magick(args){const r=spawnSync("magick",args,{maxBuffer:20000000});if(r.status!==0)throw Error(r.stderr.toString());return r.stdout;}
const [width,height]=magick(["identify","-format","%w %h",source]).toString().split(" ").map(Number);
const alpha=magick([source,"-alpha","extract","-depth","8","gray:-"]);
const edges=[0];
for(let col=1;col<3;col++){
  const candidates=[];
  for(let x=Math.floor(col*width/3-width/12);x<col*width/3+width/12;x++){
    let clear=true;for(let y=0;y<height;y++)if(alpha[y*width+x]>24){clear=false;break;}
    if(clear)candidates.push(x);
  }
  if(!candidates.length)throw Error("Missing transparent gutter");
  edges.push(candidates[Math.floor(candidates.length/2)]);
}
edges.push(width);
let top=height,bottom=0;
const frames=[];
for(let col=0;col<3;col++){
  let left=width,right=0;
  for(let y=0;y<height;y++)for(let x=edges[col];x<edges[col+1];x++)if(alpha[y*width+x]>24){
    left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
    if(x<=edges[col]+1||x>=edges[col+1]-2||y<2||y>=height-2)throw Error(`Clipped pose ${col}`);
  }
  if(right<=left)throw Error(`Empty pose ${col}`);
  frames.push({x:left-2,w:right-left+5});
}
const art={sheet:"wenboConversation",frames:frames.map(f=>({...f,y:top-2,h:bottom-top+5}))};
writeFileSync("public/data/wenbo-conversation-art.js","// Generated by scripts/prepare-wenbo-conversation.js.\nexport const wenboConversationArt = "+JSON.stringify(art,null,2)+";\n");
magick([source,"-strip","-quality","85","-define","webp:alpha-quality=100","public/assets/optimized/wenbo-conversation-away-v1.webp"]);
console.log("Prepared Wenbo's three rear-facing conversation poses.");
