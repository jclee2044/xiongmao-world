// Trace alpha bounds and encode the original generated atlases without resizing.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { stationTravelers } from "../public/data/station-travelers.js";
const sheets = {
  travelersA: {
    letter: "a",
    rows: [0, 322, 617, 939, 1243, 1619],
    centers: [198, 492, 786],
    columns: [0, 345, 639, 971],
  },
  travelersB: {
    letter: "b",
    rows: [0, 324, 638, 951, 1265, 1619],
    centers: [222, 493, 758],
    columns: [0, 356, 625, 971],
  },
};
const output = {};
for (const [sheet, { letter, rows, centers, columns }] of Object.entries(
  sheets,
)) {
  const path = `public/assets/characters/station-travelers-${letter}.png`;
  const result = spawnSync(
    "magick",
    [path, "-alpha", "extract", "-depth", "8", "gray:-"],
    { maxBuffer: 10000000 },
  );
  if (result.status !== 0) throw Error(result.stderr.toString());
  const alpha = result.stdout;
  for (const traveler of stationTravelers.filter((t) => t.sheet === sheet)) {
    const row = traveler.row;
    let top = rows[row + 1],
      bottom = rows[row],
      halfWidth = 0;
    for (let col = 0; col < 3; col++)
      for (let y = rows[row]; y < rows[row + 1]; y++)
        for (let x = columns[col]; x < columns[col + 1]; x++)
          if (alpha[y * 971 + x] > 24) {
            top = Math.min(top, y);
            bottom = Math.max(bottom, y);
            halfWidth = Math.max(halfWidth, Math.abs(x - centers[col]));
          }
    top = Math.max(rows[row], top - 2);
    bottom = Math.min(rows[row + 1], bottom + 3);
    halfWidth += 2;
    output[traveler.id] = {
      sheet,
      frames: centers.map((x) => ({
        x: x - halfWidth,
        y: top,
        w: halfWidth * 2,
        h: bottom - top,
      })),
    };
  }
  const encoded = spawnSync("magick", [
    path,
    "-strip",
    "-quality",
    "85",
    "-define",
    "webp:alpha-quality=100",
    `public/assets/optimized/station-travelers-${letter}.webp`,
  ]);
  if (encoded.status !== 0) throw Error(encoded.stderr.toString());
}
writeFileSync(
  "public/data/station-traveler-art.js",
  "// Generated by scripts/prepare-station-travelers.js; fixed anchors preserve feet across poses.\nexport const travelerArt = " +
    JSON.stringify(output, null, 2) +
    ";\n",
);
console.log("Prepared 10 travelers × 3 poses with transparent WebP atlases.");
