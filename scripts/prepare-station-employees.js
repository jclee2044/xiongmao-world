// Locate the transparent atlas cells without altering generated artwork/alpha.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const source = "public/assets/characters/station-employee-poses-v2.png";
function magick(args) {
  const r = spawnSync("magick", args, { maxBuffer: 30000000 });
  if (r.status !== 0) throw Error(r.stderr.toString());
  return r.stdout;
}
const [width, height] = magick(["identify", "-format", "%w %h", source]).toString().split(" ").map(Number);
const alpha = magick([source, "-alpha", "extract", "-depth", "8", "gray:-"]);
// Find actual clear gutters near thirds (the generated grid can drift a few pixels).
const rowEdges = [0];
for (let row = 1; row < 3; row++) {
  const clear = [];
  for (let y = Math.floor(row * height / 3 - 20); y < row * height / 3 + 20; y++) {
    if (alpha.subarray(y * width, (y + 1) * width).every(a => a <= 24)) clear.push(y);
  }
  if (!clear.length) throw Error("Missing transparent row gutter");
  rowEdges.push(clear[Math.floor(clear.length / 2)]);
}
rowEdges.push(height);
const rows = [];
for (let row = 0; row < 3; row++) {
  const frames = [];
  for (let col = 0; col < 3; col++) {
    const x0 = Math.floor(col * width / 3), x1 = Math.floor((col + 1) * width / 3);
    const y0 = rowEdges[row], y1 = rowEdges[row + 1];
    let left = width, right = 0, top = height, bottom = 0;
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      if (alpha[y * width + x] <= 24) continue;
      if (x <= x0 + 1 || x >= x1 - 2 || y <= y0 + 1 || y >= y1 - 2) throw Error(`Clipped frame ${row},${col}`);
      left = Math.min(left, x); right = Math.max(right, x);
      top = Math.min(top, y); bottom = Math.max(bottom, y);
    }
    if (right <= left) throw Error(`Empty frame ${row},${col}`);
    frames.push({ x: left - 2, y: top - 2, w: right - left + 5, h: bottom - top + 5 });
  }
  // Common height, bottom-aligned, prevents a nod from resizing the body.
  const h = Math.max(...frames.map(f => f.h));
  rows.push({ sheet: "stationEmployeePoses", frames: frames.map(f => ({ ...f, y: f.y + f.h - h, h })) });
}
writeFileSync("public/data/station-employee-art.js", "// Generated by scripts/prepare-station-employees.js.\nexport const stationEmployeeArt = " + JSON.stringify(rows, null, 2) + ";\n");
magick([source, "-strip", "-quality", "85", "-define", "webp:alpha-quality=100", "public/assets/optimized/station-employee-poses-v2.webp"]);
console.log("Prepared nine employee poses with shared row scale and grounded feet.");
